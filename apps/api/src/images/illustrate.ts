/**
 * Attach illustrations to a generated deck.
 *
 * Images are best-effort: a provider failure leaves the question intact and
 * adds a warning, because an illustration is never required to answer.
 */
import type { AiWarning } from '@mengyin/ai-contract';
import type { Deck, ImageMedia, Question } from '@mengyin/core';
import type { QuestionImageRequest } from '../generation/types';
import type { ImageAttestation } from './attest';
import type { ImageGenerator } from './generator';
import type { ImageSearcher } from './search';

export interface IllustrationResult {
  requested: number;
  /** Images attached, whether from web search or the image model. */
  generated: number;
  /** Attached from web image search. */
  searched: number;
  failed: number;
  warnings: AiWarning[];
}

export interface IllustrateOptions {
  max: number;
  concurrency?: number;
  signal?: AbortSignal;
  onProgress?: (done: number, total: number) => void;
  /** Sign the generated bytes so a modified upload can be rejected later. */
  attest?: (image: string) => Promise<ImageAttestation | null>;
  /** Optional web image search; tried before the image model. */
  search?: ImageSearcher | null;
}

export async function illustrateDeck(
  deck: Deck,
  requests: readonly QuestionImageRequest[],
  generator: ImageGenerator | null,
  options: IllustrateOptions,
): Promise<IllustrationResult> {
  const limit = Math.max(0, Math.min(options.max, requests.length));
  const selected = requests.slice(0, limit);
  const warnings: AiWarning[] = [];
  if (selected.length === 0) {
    return { requested: requests.length, generated: 0, searched: 0, failed: 0, warnings };
  }

  const byId = new Map<string, Question>(deck.questions.map((question) => [question.id, question]));
  const queue = [...selected];
  let generated = 0;
  let searched = 0;
  let failed = 0;
  let done = 0;

  const attach = (question: Question, media: ImageMedia): void => {
    question.media = [...(question.media ?? []), media];
  };

  const worker = async (): Promise<void> => {
    for (;;) {
      const request = queue.shift();
      if (!request) return;
      try {
        const question = byId.get(request.questionId);
        // A real reference photo is better than a generated guess for a place,
        // object or historical scene. Search is skipped when no query was
        // supplied, and a miss falls through to the image model.
        if (request.search && options.search) {
          const hit = await options.search
            .search(request.search, options.signal ? { signal: options.signal } : {})
            .catch(() => null);
          if (hit) {
            if (question) {
              attach(question, {
                type: 'image',
                src: hit.image,
                ...(request.alt ? { alt: request.alt } : {}),
                credit: hit.credit,
                sourceUrl: hit.sourceUrl,
                license: hit.license,
              });
            }
            generated += 1;
            searched += 1;
            continue;
          }
          if (request.searchOnly) {
            throw new Error(
              `No reliable reference photo was found for "${request.search}". A generated guess was not used.`,
            );
          }
        }
        if (request.searchOnly) {
          throw new Error('This question needs a real reference photo, but image search is not configured.');
        }
        if (!generator) {
          throw new Error('Web image search found no usable photo and no image generator is configured.');
        }
        const result = await generator.generate(request.prompt, {
          ...(request.alt ? { alt: request.alt } : {}),
          ...(options.signal ? { signal: options.signal } : {}),
        });
        if (question) {
          const alt = request.alt ?? result.alt ?? '';
          // Attestation is best-effort: a missing key must not lose the image.
          const attestation = options.attest ? await options.attest(result.image).catch(() => null) : null;
          attach(question, {
            type: 'image',
            src: result.image,
            ...(alt ? { alt } : {}),
            ...(attestation ? { digest: attestation.digest, signature: attestation.signature } : {}),
          });
        }
        generated += 1;
      } catch (error) {
        failed += 1;
        const message = error instanceof Error ? error.message : String(error);
        warnings.push({
          code: 'image',
          message: `Question ${request.questionId} has no illustration: ${message.slice(0, 180)}`,
        });
      } finally {
        done += 1;
        options.onProgress?.(done, selected.length);
      }
    }
  };

  const concurrency = Math.max(1, Math.min(options.concurrency ?? 2, selected.length));
  await Promise.all(Array.from({ length: concurrency }, worker));
  return { requested: requests.length, generated, searched, failed, warnings };
}
