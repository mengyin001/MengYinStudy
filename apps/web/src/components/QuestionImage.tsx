import { useEffect, useState } from 'react';
import type { ImageMedia, QuestionMedia } from '@mengyin/core';
import { backend } from '@/services';
import { verifyStoredImage } from '@/services/mediaProof';
import { isUserMediaSrc, userMediaPath } from '@/services/supabase/userMedia';
import { FigureView } from './FigureView';

/** 1×1 transparent GIF, shown until a private object has a signed URL. */
const PLACEHOLDER =
  'data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7';

interface QuestionImageProps {
  media: QuestionMedia;
  className?: string;
  loading?: 'eager' | 'lazy';
}

/**
 * Renders inline images and figures directly, and resolves `storage:` markers
 * through the private bucket. The marker stays in the deck data, so re-saving a
 * cloud deck never writes an expiring signed URL back to the database.
 *
 * A photo generated by the AI service carries a digest and a signature. For
 * stored objects the bytes are fetched, hashed and verified before they are
 * shown, so an object swapped in Storage is never displayed. Legacy images
 * without an attestation render normally.
 */
export function QuestionImage({ media, className, loading = 'lazy' }: QuestionImageProps) {
  if (media.type === 'figure') {
    return <FigureView spec={media.figure} alt={media.alt} className={className} />;
  }
  return <StoredImage media={media} className={className} loading={loading} />;
}

function StoredImage({
  media,
  className,
  loading,
}: {
  media: ImageMedia;
  className?: string;
  loading: 'eager' | 'lazy';
}) {
  const [src, setSrc] = useState(() => (isUserMediaSrc(media.src) ? null : media.src));
  const [failed, setFailed] = useState(false);
  const attested = Boolean(media.digest && media.signature);

  useEffect(() => {
    let active = true;
    let objectUrl: string | null = null;
    setFailed(false);

    if (!isUserMediaSrc(media.src)) {
      setSrc(media.src);
      return () => {
        active = false;
      };
    }

    const path = userMediaPath(media.src);
    if (!path) {
      setSrc(null);
      setFailed(true);
      return () => {
        active = false;
      };
    }

    setSrc(null);
    void (async () => {
      try {
        const url = await backend.userMedia.signedUrl(path);
        if (!active) return;
        if (!url) {
          setFailed(true);
          return;
        }
        if (!attested) {
          setSrc(url);
          return;
        }
        const response = await fetch(url);
        if (!response.ok) throw new Error('The image could not be downloaded.');
        const bytes = new Uint8Array(await response.arrayBuffer());
        const valid = await verifyStoredImage(bytes, media);
        if (!active) return;
        if (!valid) {
          setFailed(true);
          return;
        }
        const type = response.headers.get('content-type') ?? 'image/png';
        objectUrl = URL.createObjectURL(new Blob([bytes], { type }));
        setSrc(objectUrl);
      } catch {
        if (active) setFailed(true);
      }
    })();

    return () => {
      active = false;
      if (objectUrl) URL.revokeObjectURL(objectUrl);
    };
  }, [media.src, media.digest, media.signature, attested]);

  if (failed) {
    // The object is missing, or its bytes no longer match the signature. An
    // illustration is never required to answer, so the question renders as if
    // it never had one instead of leaving an empty frame in the card.
    return null;
  }

  const image = (
    <img
      className={className}
      src={src ?? PLACEHOLDER}
      alt={media.alt ?? ''}
      loading={loading}
      onError={() => setFailed(true)}
    />
  );
  if (!media.credit) return image;
  const href = media.sourceUrl?.startsWith('https://') ? media.sourceUrl : null;
  return (
    <span className="media-figure">
      {image}
      <small className="media-credit">
        {href ? (
          <a href={href} target="_blank" rel="noreferrer">
            {media.credit}
          </a>
        ) : (
          media.credit
        )}
      </small>
    </span>
  );
}
