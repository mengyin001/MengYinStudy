import { useEffect, useRef, useState } from 'react';
import type { ImageMedia, QuestionMedia } from '@mengyin/core';
import { backend } from '@/services';
import { verifyStoredImage } from '@/services/mediaProof';
import { isUserMediaSrc, userMediaPath } from '@/services/supabase/userMedia';
import { useApp } from '@/state/AppContext';
import { FigureView } from './FigureView';

/** 1×1 transparent GIF, shown until a private object has a signed URL. */
const PLACEHOLDER =
  'data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7';

/**
 * How long an illustration may take before the card admits that it is still
 * loading. Cached images resolve well inside this window, so paging through a
 * already-seen deck never flashes a spinner.
 */
const SPINNER_DELAY_MS = 160;

type StageState = 'pending' | 'loading' | 'ready';

interface QuestionImageProps {
  media: QuestionMedia;
  className?: string;
  loading?: 'eager' | 'lazy';
}

/**
 * Renders inline images and figures directly, and resolves `storage:` markers
 * through the private bucket. The marker stays in the deck data, so re-saving a
 * cloud deck never writes an expiring signed URL back to the database.
 *
 * A photo generated by the AI service carries a digest and a signature. For
 * stored objects the bytes are fetched, hashed and verified before they are
 * shown, so an object swapped in Storage is never displayed. Legacy images
 * without an attestation render normally.
 */
export function QuestionImage({ media, className, loading = 'lazy' }: QuestionImageProps) {
  if (media.type === 'figure') {
    return <FigureView spec={media.figure} alt={media.alt} className={className} />;
  }
  return <StoredImage media={media} className={className} loading={loading} />;
}

function StoredImage({
  media,
  className,
  loading,
}: {
  media: ImageMedia;
  className?: string;
  loading: 'eager' | 'lazy';
}) {
  const { t } = useApp();
  const [src, setSrc] = useState<string | null>(() => (isUserMediaSrc(media.src) ? null : media.src));
  const [failed, setFailed] = useState(false);
  // Tracked by source, so a new question's illustration is "not loaded" the
  // instant its URL changes and a re-render never revives a stale spinner.
  const [loadedSrc, setLoadedSrc] = useState<string | null>(null);
  const [slow, setSlow] = useState(false);
  const imageRef = useRef<HTMLImageElement | null>(null);
  const attested = Boolean(media.digest && media.signature);
  const loaded = src !== null && loadedSrc === src;

  useEffect(() => {
    let active = true;
    let objectUrl: string | null = null;
    setFailed(false);

    if (!isUserMediaSrc(media.src)) {
      setSrc(media.src);
      return () => {
        active = false;
      };
    }

    const path = userMediaPath(media.src);
    if (!path) {
      setSrc(null);
      setFailed(true);
      return () => {
        active = false;
      };
    }

    setSrc(null);
    void (async () => {
      try {
        const url = await backend.userMedia.signedUrl(path);
        if (!active) return;
        if (!url) {
          setFailed(true);
          return;
        }
        if (!attested) {
          setSrc(url);
          return;
        }
        const response = await fetch(url);
        if (!response.ok) throw new Error('The image could not be downloaded.');
        const bytes = new Uint8Array(await response.arrayBuffer());
        const valid = await verifyStoredImage(bytes, media);
        if (!active) return;
        if (!valid) {
          setFailed(true);
          return;
        }
        const type = response.headers.get('content-type') ?? 'image/png';
        objectUrl = URL.createObjectURL(new Blob([bytes], { type }));
        setSrc(objectUrl);
      } catch {
        if (active) setFailed(true);
      }
    })();

    return () => {
      active = false;
      if (objectUrl) URL.revokeObjectURL(objectUrl);
    };
  }, [media.src, media.digest, media.signature, attested]);

  // A question is often reopened with its illustration already in the browser
  // cache, and the load event can land before React attaches its listener.
  useEffect(() => {
    const image = imageRef.current;
    if (src && image && image.complete && image.naturalWidth > 0) setLoadedSrc(src);
  }, [src]);

  // Only admit to loading after a short grace period: a cached or inline image
  // appears immediately, and a spinner that lives for one frame is noise.
  useEffect(() => {
    if (loaded || failed) {
      setSlow(false);
      return;
    }
    const timer = window.setTimeout(() => setSlow(true), SPINNER_DELAY_MS);
    return () => window.clearTimeout(timer);
  }, [loaded, failed, src]);

  if (failed) {
    // The object is missing, or its bytes no longer match the signature. An
    // illustration is never required to answer, so the question renders as if
    // it never had one instead of leaving an empty frame in the card.
    return null;
  }

  const state: StageState = loaded ? 'ready' : slow ? 'loading' : 'pending';

  const image = (
    <span className="media-stage" data-state={state} aria-busy={!loaded}>
      {state === 'loading' ? (
        <span className="media-loading" key="loading">
          <span className="media-loading__ring" aria-hidden="true" />
          <span className="media-loading__label" role="status">
            {t('common.imageLoading')}
          </span>
        </span>
      ) : null}
      <img
        key="media"
        ref={imageRef}
        className={className}
        src={src ?? PLACEHOLDER}
        alt={media.alt ?? ''}
        loading={loading}
        onLoad={() => {
          if (src) setLoadedSrc(src);
        }}
        onError={() => setFailed(true)}
      />
    </span>
  );
  if (!media.credit) return image;
  const href = media.sourceUrl?.startsWith('https://') ? media.sourceUrl : null;
  return (
    <span className="media-figure">
      {image}
      <small className="media-credit">
        {href ? (
          <a href={href} target="_blank" rel="noreferrer">
            {media.credit}
          </a>
        ) : (
          media.credit
        )}
      </small>
    </span>
  );
}
